//! Renders a library as the text of one Lua file, and a map from each of its lines to the
//! C++ line it came from.

use crate::decl::{Comment, Field};
use crate::doc::Source;
use crate::library::Item;
use crate::scan::Syntax;
use crate::text::{Line, Src, commented, join, trimmed};

/// Options that affect extraction and the generated text.
#[derive(Debug, Clone, Default)]
pub struct Options {
    /// Base URL for source links, e.g. `https://github.com/org/repo/blob/<sha>/`.
    pub repo: Option<String>,
    /// The comments that are docs.
    pub syntax: Syntax,
}

/// One generated Lua file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rendered {
    pub lua: String,
    /// For each line of `lua`, the C++ line (1-based) it came from. Lines with no source,
    /// such as the header and blank lines, are `None`.
    pub line_map: Vec<Option<Src>>,
}

pub fn emit(items: &[Item], options: &Options) -> Rendered {
    let mut lines: Vec<Line> = header().lines().map(Line::generated).collect();
    for item in items {
        let item_lines = render_item(item, options);
        if !item_lines.is_empty() {
            lines.push(Line::generated(""));
            lines.extend(item_lines);
        }
    }
    let mut lua: String = lines
        .iter()
        .map(|l| l.text.as_str())
        .collect::<Vec<_>>()
        .join("\n");
    lua.push('\n');
    Rendered {
        lua,
        line_map: lines.iter().map(|l| l.src.clone()).collect(),
    }
}

/// `@generated` is a common (informal) marker for generated files. emmylua reads even a plain
/// `--` comment directly above a symbol as its description, so the blank line after the header
/// matters.
fn header() -> String {
    format!(
        r#"---@meta
-- ------------
-- @generated
-- AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
-- Generated by: {name} v{version} ({repository})
-- ------------"#,
        name = env!("CARGO_PKG_NAME"),
        version = env!("CARGO_PKG_VERSION"),
        repository = env!("CARGO_PKG_REPOSITORY"),
    )
}

fn render_item(item: &Item, options: &Options) -> Vec<Line> {
    match item {
        Item::Function {
            path,
            params,
            comment,
            source,
            line,
        } => {
            let code = format!("function {path}({}) end", params.join(", "));
            with_comment(
                comment,
                source,
                options,
                vec![Line::new(code, line.clone())],
            )
        }
        Item::Table {
            path,
            is_local,
            comment,
            fields,
            source,
            line,
        } => {
            let local = if *is_local { "local " } else { "" };
            let code = if fields.is_empty() {
                vec![Line::new(format!("{local}{path} = {{}}"), line.clone())]
            } else {
                let mut code = vec![Line::new(format!("{local}{path} = {{"), line.clone())];
                for (i, field) in fields.iter().enumerate() {
                    if i > 0 {
                        code.push(Line::generated(""));
                    }
                    let mut field = render_field(field, InTable::Yes, options);
                    if i + 1 < fields.len()
                        && let Some(last) = field.last_mut()
                    {
                        last.text.push(',');
                    }
                    code.extend(field);
                }
                code.push(Line::new("}", line.clone()));
                code
            };
            with_comment(comment, source, options, code)
        }
        Item::Field(field) => render_field(field, InTable::No, options),
        Item::Comment { comment, source } => commented(comment_lines(comment, source, options), ""),
    }
}

/// `---description`, a blank line, `---@tags`, then `code`.
fn with_comment(
    comment: &Comment,
    source: &Source,
    options: &Options,
    code: Vec<Line>,
) -> Vec<Line> {
    let mut lines = commented(comment_lines(comment, source, options), "");
    lines.extend(code);
    lines
}

fn comment_lines(comment: &Comment, source: &Source, options: &Options) -> Vec<Line> {
    let mut lines = trimmed(comment.description.clone());
    let mut tags = comment.tags.clone();
    tags.extend(see_link(source, options));
    if !tags.is_empty() {
        if !lines.is_empty() {
            lines.push(Line::generated(""));
        }
        lines.extend(tags);
    }
    lines
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum InTable {
    Yes,
    No,
}

/// A literal becomes the value (`STOP = 0`); any other type becomes `---@type` and a placeholder
/// value: `{}` for a table, else `nil`. A standalone `nil` that the type doesn't allow is marked,
/// so emmylua doesn't report it: the library declares the field, it doesn't set it. (Neither
/// emmylua nor LuaLS checks a field in a table constructor against its `---@type`.)
///
/// A field's own description and its doc's description are both kept. As in v3, a field in a
/// table puts its own first, and a standalone field puts the doc's first.
fn render_field(field: &Field, in_table: InTable, options: &Options) -> Vec<Line> {
    let (own, doc) = (
        field.typed.description.clone(),
        field.comment.description.clone(),
    );
    let (mut lines, rest) = match in_table {
        InTable::Yes => (own, doc),
        InTable::No => (doc, own),
    };
    join(&mut lines, rest);
    let indent = if in_table == InTable::Yes { "\t" } else { "" };
    let mut placeholder_nil = false;
    let value = match &field.typed.literal {
        Some(literal) => literal.clone(),
        None => {
            let mut ty = field.typed.ty.clone();
            let first = format!("@type {}", ty[0].text);
            ty[0].text = first.trim_end().to_string();
            join(&mut lines, ty);
            if field.typed.is_table {
                "{}".to_string()
            } else {
                placeholder_nil = in_table == InTable::No && !field.typed.is_nullable;
                "nil".to_string()
            }
        }
    };
    let mut lines = trimmed(lines);
    lines.extend(field.comment.tags.iter().cloned());
    lines.extend(see_link(&field.source, options));
    if placeholder_nil {
        lines.push(Line::generated(
            "@diagnostic disable-next-line: assign-type-mismatch",
        ));
    }
    let mut out = commented(lines, indent);
    out.push(Line::new(
        format!("{indent}{} = {value}", field.path),
        field.line.clone(),
    ));
    out
}

/// `@see [LuaSyncedRead.cpp#L10-L20](<repo>/rts/Lua/LuaSyncedRead.cpp#L10-L20)`, mapped to
/// the first line of the doc it links to.
fn see_link(source: &Source, options: &Options) -> Option<Line> {
    let repo = options.repo.as_deref()?;
    let file = source.path.rsplit('/').next().unwrap_or(&source.path);
    let lines = format!("#L{}-L{}", source.start.line, source.end.line);
    let base = repo.trim_end_matches('/');
    let text = format!("@see [{file}{lines}]({base}/{}{lines})", source.path);
    Some(Line::new(
        text,
        Some(Src::new(source.path.as_str(), source.start.line)),
    ))
}
